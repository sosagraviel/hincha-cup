import type { FullConfig, FullResult, Reporter, Suite, TestCase, TestResult } from '@playwright/test/reporter';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const clean = (m?: string) => m?.replace(/\x1b\[[0-9;]*m/g, '').split('\n')[0]?.slice(0, 200);

// Known bugs registry written by QACluster: { "BUG-001": { "signature": "text or /regex/ the failure must contain", "title": "…" } }.
// A `@fail @BUG-NNN` scenario that fails with a DIFFERENT error is not the known bug: it is reported as a new failure.
type KnownBug = { signature?: string; title?: string };
const loadKnownBugs = (): Record<string, KnownBug> => {
  try { return existsSync('.qa-cluster/known-bugs.json') ? JSON.parse(readFileSync('.qa-cluster/known-bugs.json', 'utf8')) : {}; }
  catch { return {}; }
};
const matches = (sig: string, text: string) => {
  const re = sig.match(/^\/(.*)\/([a-z]*)$/);
  return re ? new RegExp(re[1], re[2]).test(text) : text.includes(sig);
};

type Row = { id: string; title: string; file: string; outcome: string; duration: number; bug?: string; error?: string; testgraph?: string };

/**
 * Per-run summary (generated by QACluster, runs without it).
 * Writes test-results/summary.md and summary.json and, in GitHub Actions, the job summary.
 * States: passed · failed · flaky · skipped · known-bug (scenario tagged @fail @BUG-NNN) · bug-fixed? (a known-bug that passed)
 *   · known-bug-other-error (a known-bug scenario that failed with an error that is not the bug's signature: a new failure)
 *   · known-intermittent (tagged @intermittent @BUG-NNN, skipped in the normal run) · intermittent-fail / intermittent-pass
 *   (with RUN_INTERMITTENT=1: they run and the failure rate per bug is reported; they never turn the suite red).
 */
export default class SummaryReporter implements Reporter {
  private rows = new Map<string, Row>();
  private knownBugs = loadKnownBugs();
  private setupErrors: string[] = [];
  private all: TestCase[] = [];
  private intermittent = new Map<string, { bug: string; caseId: string; runs: number; failures: number }>();

  onBegin(_config: FullConfig, suite: Suite): void {
    this.all = suite.allTests().filter((t) => t.parent.project()?.name !== 'setup');
  }

  onTestEnd(test: TestCase, result: TestResult): void {
    if (test.parent.project()?.name === 'setup') {
      if (result.status !== 'passed' && result.status !== 'skipped')
        this.setupErrors.push(`${test.title}: ${clean(result.error?.message) ?? result.status}`);
      return;
    }
    const annotations = [...test.annotations, ...((result as { annotations?: TestCase['annotations'] }).annotations ?? [])];
    // Known bugs: Gherkin tags `@fail @BUG-NNN` (playwright-bdd turns @fail into test.fail()); annotations as fallback
    // A scenario can carry several bugs (`@fail @BUG-002 @BUG-005`, most severe first): all are listed and any of their
    // signatures is accepted; it only counts as fixed when the scenario passes, i.e. all of them are fixed.
    const tagBugs = test.tags.filter((t) => /^@BUG-\d+$/.test(t)).map((t) => t.slice(1));
    const annBug = annotations.find((a) => a.type === 'fail' && /BUG-\d+/.test(a.description ?? ''))?.description?.match(/BUG-\d+/)?.[0];
    const isIntermittent = test.tags.includes('@intermittent');
    const bugIds = tagBugs.length ? tagBugs : annBug ? [annBug] : [];
    const bug = test.expectedStatus === 'failed' || isIntermittent ? (bugIds.length ? bugIds.join(', ') : 'BUG-?') : undefined;
    const testgraph = test.tags.find((t) => t.startsWith('@tg-'))?.slice(4) ?? annotations.find((a) => a.type === 'testgraph')?.description;
    const outcome = test.outcome();
    let status: string =
      outcome === 'flaky' ? 'flaky' : outcome === 'skipped' ? 'skipped' : outcome === 'expected' ? 'passed' : 'failed';
    let otherError: string | undefined;
    if (bug && outcome === 'expected') {
      status = 'known-bug';
      const sigs = bugIds.map((b) => this.knownBugs[b]?.signature).filter((x): x is string => !!x);
      const errors = (result.errors?.length ? result.errors : result.error ? [result.error] : [])
        .map((e) => (e.message ?? '').replace(/\x1b\[[0-9;]*m/g, ''));
      const isKnown = (m: string) => sigs.some((sig) => matches(sig, m));
      // Each known bug produces its own error; any other error in the same run is a new problem it would mask
      const others = sigs.length ? errors.filter((m) => !isKnown(m)) : [];
      if (sigs.length && (others.length || !errors.some(isKnown))) {
        status = 'known-bug-other-error';
        otherError = clean(others[0] ?? errors[0]) ?? 'failed without the known bug signature';
      }
    }
    if (bug && outcome === 'unexpected' && result.status === 'passed') status = 'bug-fixed?';
    if (isIntermittent) {
      if (outcome === 'skipped') status = 'known-intermittent';
      else {
        status = result.status === 'passed' ? 'intermittent-pass' : 'intermittent-fail';
        const key = `${bug}:${test.title}`;
        const agg = this.intermittent.get(key) ?? { bug: bug!, caseId: test.title.split(' ')[0], runs: 0, failures: 0 };
        agg.runs += 1; if (status === 'intermittent-fail') agg.failures += 1;
        this.intermittent.set(key, agg);
      }
    }
    const [id, ...rest] = test.title.split(' ');
    this.rows.set(test.id, {
      id, title: rest.join(' '), file: test.location.file.replace(process.cwd() + '/', ''),
      outcome: status, duration: result.duration, bug, testgraph,
      error: status === 'failed' ? clean(result.error?.message) : otherError,
    });
  }

  async onEnd(result: FullResult): Promise<{ status?: FullResult['status'] } | void> {
    for (const t of this.all) {
      if (this.rows.has(t.id)) continue;
      const [id, ...rest] = t.title.split(' ');
      this.rows.set(t.id, { id, title: rest.join(' '), file: t.location.file.replace(process.cwd() + '/', ''),
        outcome: 'not-run', duration: 0, error: this.setupErrors.length ? 'setup failed' : 'did not run' });
    }
    const rows = [...this.rows.values()].sort((a, b) => a.id.localeCompare(b.id));
    const count = (s: string) => rows.filter((r) => r.outcome === s).length;
    const totals = { passed: count('passed'), failed: count('failed'), flaky: count('flaky'), knownBugs: count('known-bug'),
      bugFixed: count('bug-fixed?'), otherError: count('known-bug-other-error'), skipped: count('skipped'), notRun: count('not-run'),
      knownIntermittent: count('known-intermittent'), total: rows.length - count('intermittent-pass') - count('intermittent-fail'),
      setupErrors: this.setupErrors, status: result.status };
    const intermittent = [...this.intermittent.values()];
    // Failures of @intermittent scenarios are expected (they are known bugs): they do not make the run broken
    const otherFailures = rows.some((r) => r.outcome === 'failed') || (result.status !== 'passed' && !intermittent.some((i) => i.failures));
    const broken = totals.failed || totals.bugFixed || totals.otherError || totals.notRun || this.setupErrors.length || otherFailures;
    const icon = broken ? '❌' : totals.flaky ? '⚠️' : '✅';
    const md = [
      totals.total === 0 && intermittent.length ? '## 🔁 E2E — known intermittent bugs check' : `## ${icon} E2E — ${totals.passed}/${totals.total} OK`,
      '',
      '| Passed | Failed | Flaky | Known bugs | Known bug, other error | Known intermittent | Bug fixed? | Not run | Skipped |',
      '|---|---|---|---|---|---|---|---|---|',
      `| ${totals.passed} | ${totals.failed} | ${totals.flaky} | ${totals.knownBugs} | ${totals.otherError} | ${totals.knownIntermittent} | ${totals.bugFixed} | ${totals.notRun} | ${totals.skipped} |`,
      ...(intermittent.length ? ['', '**Intermittent bugs (RUN_INTERMITTENT=1):**', '', '| Bug | Case | Failed | Hint |', '|---|---|---|---|',
        ...intermittent.map((i) => `| ${i.bug} | ${i.caseId} | ${i.failures}/${i.runs} | ${i.failures === 0 && i.runs >= 4 ? 'bug-fixed? remove the tags' : 'still reproduces'} |`)] : []),
      '',
      ...(this.setupErrors.length ? ['**Setup failed** (login / storageState):', ...this.setupErrors.map((e) => `- ${e}`), ''] : []),
      ...(rows.some((r) => !['passed', 'intermittent-pass', 'intermittent-fail'].includes(r.outcome))
        ? ['| Case | Status | Detail |', '|---|---|---|',
           ...rows.filter((r) => !['passed', 'intermittent-pass', 'intermittent-fail'].includes(r.outcome))
             .map((r) => `| ${r.id} ${r.title} | ${r.outcome} | ${r.outcome === 'known-bug-other-error' ? `${r.bug}: ${r.error}` : (r.bug ?? r.error ?? '')} |`), '']
        : []),
      totals.bugFixed ? '> A test marked as a known bug passed: check whether the bug was fixed and remove `test.fail`.\n' : '',
      totals.otherError ? '> A known-bug scenario failed with a different error than its bug: that is a new failure the `@fail` tag would otherwise hide.\n' : '',
      'Full report: `e2e/playwright-report/index.html`',
    ].join('\n');
    mkdirSync('test-results', { recursive: true });
    writeFileSync('test-results/summary.md', md + '\n');
    writeFileSync('test-results/summary.json', JSON.stringify({ totals, intermittent, rows }, null, 2));
    if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, md + '\n');
    // Playwright counts a @fail scenario that failed for another reason as "expected": make the run red ourselves
    if (totals.otherError && result.status === 'passed') return { status: 'failed' as const };
  }

  printsToStdio(): boolean { return false; }
}
